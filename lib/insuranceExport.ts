/**
 * Compute the Actual Cash Value (depreciated value) for a home item.
 * Uses straight-line depreciation with a 10% floor so nothing hits zero.
 */
export function computeAcv(item: HomeItem): number {
  const rc = item.replacementCostUsd ?? 0;
  if (rc <= 0) return 0;
  const ratio = item.typicalLifespanYears > 0
    ? item.estimatedAgeYears / item.typicalLifespanYears
    : 0;
  return Math.round(rc * Math.max(0.1, 1 - ratio));
}

// --------------------------------------------------------------------------
// Photo loading helper
// --------------------------------------------------------------------------

async function loadPhotoBase64(uri: string | undefined): Promise<string | null> {
  if (!uri) return null;
  try {
    // Skip remote URLs — only inline local file:// photos
    if (!uri.startsWith("file://")) return null;
    const info = await FileSystem.getInfoAsync(uri);
    if (!info.exists) return null;
    return await FileSystem.readAsStringAsync(uri, {
      encoding: FileSystem.EncodingType.Base64,
    });
  } catch {
    return null;
  }
}

