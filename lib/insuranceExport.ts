// --------------------------------------------------------------------------
// Export function
// --------------------------------------------------------------------------

export async function exportInsurancePdf(args: {
  items: HomeItem[];
  home: Home | null;
  user: User | null;
}): Promise<string> {
  const { items, home, user } = args;

  // Load photos in parallel
  const itemsWithPhotos: ItemWithPhoto[] = await Promise.all(
    items.map(async (item) => {
      const photoData = await loadPhotoBase64(item.photoUri);
      return { item, photoData, acv: computeAcv(item) };
    })
  );

  const totalReplacement = items.reduce(
    (sum, i) => sum + (i.replacementCostUsd ?? 0),
    0
  );
  const totalAcv = itemsWithPhotos.reduce((sum, i) => sum + i.acv, 0);

  const html = buildHtml({
    items: itemsWithPhotos,
    homeName: home?.name ?? "My Home",
    homeAddress: home?.address ?? "",
    userName: user?.name ?? "Homeowner",
    totalReplacement,
    totalAcv,
    dateGenerated: new Date().toLocaleDateString("en-US", {
      year: "numeric",
      month: "long",
      day: "numeric",
    }),
  });

  const { uri } = await Print.printToFileAsync({ html });
  return uri;
}
